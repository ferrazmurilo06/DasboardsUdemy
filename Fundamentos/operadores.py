num1 = int(input('Digite o primeiro número: '))
num2 = int(input('Digite o segundo número: '))

# Aritméticos
sum = num1 + num2
sub = num1 - num2
mult = num1 * num2
div = num1 / num2
mod = num1 % num2
expo = num1 ** num2

print(f'A soma dos números é: {sum}')
print(f'A subtração dos números é: {sub}')
print(f'A multiplicação dos números é: {mult}')
print(f'A divisão dos números é: {div}')
print(f'O resto da divisão dos números é: {mod}')
print(f'A potência dos números é: {expo}')